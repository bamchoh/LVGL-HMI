// Writes tools/skill/hml-screens/reference/widgets.md from the designer's schema.js, so that what
// the AI skill says about widgets is what the designer and the runtime know.
//
//   node tools/skill/gen_reference.js           write the file
//   node tools/skill/gen_reference.js --check   exit 1 when the file is out of date (used by the tests)
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(__dirname, 'hml-screens', 'reference', 'widgets.md');

function loadSchema() {
  const ctx = vm.createContext({});
  const src = fs.readFileSync(path.join(ROOT, 'tools', 'designer', 'renderer', 'js', 'schema.js'), 'utf8');
  vm.runInContext(src, ctx, { filename: 'schema.js' });
  return JSON.parse(JSON.stringify(vm.runInContext('SCHEMA', ctx)));
}

const code = s => '`' + s + '`';
function fieldType(f, S) {
  if (f.t === 'select') return (f.o || S.aligns).filter(o => o !== '').map(code).join(' / ');
  return { text: 'text', number: 'number', bool: 'true / false', color: 'color', size: 'size', lines: 'array of texts', points: '[[x, y], ...]',
           image: 'image path', tag: 'tag name', csv: 'array of texts', loggroup: 'data log group name', recipebook: 'recipe book name',
           screen: 'screen name', anim: 'animation', script: 'script name', code: 'Lua code' }[f.t] || f.t;
}
const jsonValue = v => code(JSON.stringify(v));
// keys the runtime takes that the designer edits elsewhere (or only as JSON)
const EXTRA = {
  trend: '`tags` items may be `{ "tag", "color" }`; `labels` (`{ "now" }`)',
  alarm_list: '`labels` (object of texts)', alarm_banner: '`labels` (object of texts)', recipe_table: '`labels` (object of texts)',
};

function generate() {
  const S = loadSchema();
  const L = [];
  L.push('# Widgets, properties, styles and actions', '',
    '<!-- Generated by tools/skill/gen_reference.js from tools/designer/renderer/js/schema.js. Do not edit by hand. -->', '',
    'Only what is listed here exists. A key that is not listed is silently ignored by the runtime.',
    'How to use bindings, actions, popups and the special widgets (alarm list, trend, recipe table): binding-and-actions.md.', '');

  L.push('## Widget types (`"type"`)', '',
    '"Created with" is what the designer writes for a new widget: sensible default sizes. Every widget also takes the common keys below.', '',
    '| type | what | own properties | created with |', '| --- | --- | --- | --- |');
  for (const [name, t] of Object.entries(S.types)) {
    const props = t.props.map(p => code(p.k) + ' (' + fieldType(p, S) + ')');
    if (t.container) props.push(code('children') + ' (array of widgets)');
    if (t.series) props.push(code('series') + ' (`[{ "tag", "color", "scale" }]`)');
    if (EXTRA[name]) props.push(EXTRA[name]);
    L.push('| ' + code(name) + ' | ' + t.label + ' | ' + (props.join(', ') || '-') + ' | ' + (Object.keys(t.def).length ? jsonValue(t.def) : '-') + ' |');
  }
  L.push('', 'A short `"bind": "tag"` binds this property of each type:', '',
    Object.entries(S.naturalBind).map(([t, k]) => code(t) + ' → ' + code(k)).join(', '), '');

  L.push('## Common keys of every widget', '', '| key | value |', '| --- | --- |');
  for (const f of S.common) L.push('| ' + code(f.k) + ' | ' + (f.t === 'size' ? 'number (px), `"50%"`, `"content"`, `"full"`' : fieldType(f, S)) + ' |');
  for (const f of S.flags.concat(S.flex)) L.push('| ' + code(f.k) + ' | ' + fieldType(f, S) + ' |');
  for (const f of S.access) L.push('| ' + code(f.k) + ' | ' + fieldType(f, S) + ' — ' + f.hint + ' |');
  L.push('');

  L.push('## Styles', '',
    'Style objects: ' + S.styleSelectors.map(code).join(', ') + '.', '',
    '| key | value |', '| --- | --- |');
  for (const [k, t] of Object.entries(S.styleKeys)) {
    const v = Array.isArray(t) ? t.map(code).join(' / ') : t === 'font' ? S.fonts.join(' / ') + ' (px)' : t === 'image' ? 'image file (path from project.json)' : t === 'bool' ? 'true / false' : t === 'color' ? 'color (`"#rrggbb"`)' : t === 'size' ? 'number, `"50%"`, `"content"`' : t;
    L.push('| ' + code(k) + ' | ' + v + ' |');
  }
  L.push('');

  L.push('## Bindings (`"bind"`)', '',
    'Kinds: ' + S.bindKinds.map(code).join(', ') + '.', '',
    'Conditions: ' + S.bindOps.filter(Boolean).map(code).join(', ') + '.', '');

  L.push('## Events and actions', '',
    'Events: ' + S.events.map(code).join(', ') + '.', '',
    '| action | keys |', '| --- | --- |');
  for (const [a, fields] of Object.entries(S.actions)) L.push('| ' + code(a) + ' | ' + (fields.map(f => code(f.k) + ' (' + fieldType(f, S) + ')').join(', ') || '-') + ' |');
  L.push('', 'An event can be put on any widget. A screen file itself takes `name`, `children`, the style objects, the common keys (`scrollable`, `flex` ..., `level`) and, for a popup, `popup`, `dim`, `w`, `h`, `x`, `y`, `align`. It takes no `bind` and no events.');
  L.push('', 'Screen change animations (`"anim"`): ' + S.anims.map(code).join(', ') + '.', '');

  L.push('## Animation (`"animate"` of any widget)', '',
    'One object or a list. Keys: ' + S.animate.keys.map(code).join(', ') + '.', '',
    '| key | value |', '| --- | --- |',
    '| `prop` | ' + S.animate.props.map(code).join(' / ') + ' |',
    '| `preset` | ' + S.animate.presets.map(code).join(' / ') + ' (fills in `prop`, `to`, `time` ...) |',
    '| `path` | ' + S.animate.paths.map(code).join(' / ') + ' |',
    '', 'How to use it: binding-and-actions.md.', '');

  L.push('## Displays', '', '| display | width | height |', '| --- | --- | --- |');
  for (const d of S.displayPresets) L.push('| ' + d.name + ' | ' + d.width + ' | ' + d.height + ' |');
  L.push('', 'Tag types: ' + S.tagTypes.map(code).join(', ') + '.', '');
  return L.join('\n');
}

// src/check_schema.inc: the same knowledge for `hml_runtime --check` (src/check.cpp), as a JSON text.
const INC = path.join(ROOT, 'src', 'check_schema.inc');
function generateInc() {
  const S = loadSchema();
  const keys = l => l.map(f => f.k);
  const data = {
    types: Object.fromEntries(Object.entries(S.types).map(([n, t]) => [n, keys(t.props).concat(t.series ? ['series'] : [])])),
    common: keys(S.common).concat(keys(S.flags), keys(S.flex), keys(S.access)),
    selectors: S.styleSelectors, style: Object.keys(S.styleKeys), events: S.events, bind: S.bindKinds, conditions: S.bindOps.filter(Boolean),
    actions: Object.fromEntries(Object.entries(S.actions).map(([n, f]) => [n, keys(f)])), anims: S.anims,
    animate: { props: S.animate.props, presets: S.animate.presets, paths: S.animate.paths, keys: S.animate.keys },
  };
  return '// Generated by tools/skill/gen_reference.js from tools/designer/renderer/js/schema.js. Do not edit by hand.\n' +
         'R"hmlschema(' + JSON.stringify(data) + ')hmlschema"\n';
}

const outputs = [[OUT, generate()], [INC, generateInc()]];
if (process.argv.includes('--check')) {
  for (const [file, text] of outputs) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== text) { console.error(path.basename(file) + ' is out of date: run  node tools/skill/gen_reference.js'); process.exit(1); }
  }
} else {
  for (const [file, text] of outputs) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log('wrote ' + path.relative(ROOT, file));
  }
}
